#!/usr/bin/env python3
"""Re-append the shared link definitions in _links.md to every docs page.

MyST link reference definitions are per-file, so each page carries a copy of
the same block at the end. Edit ``_links.md`` and run this script.
"""
import pathlib

docs = pathlib.Path(__file__).resolve().parent
links = (docs / "_links.md").read_text().strip()
MARK = "<!-- links: generated by update_links.py, edit _links.md instead -->"

for page in sorted(docs.rglob("*.md")):
    if page.name == "_links.md" or "_build" in page.parts:
        continue
    text = page.read_text()
    if MARK in text:
        text = text.split(MARK)[0]
    else:
        lines = text.rstrip().splitlines()
        while lines and (lines[-1].startswith("[") and "]: http" in lines[-1]):
            lines.pop()
        text = "\n".join(lines)
    if page.name == "sources.md":
        body = "\n".join(f"- <{l.split(': ', 1)[1]}>" for l in links.splitlines())
        text = text.split("\n- <")[0]
        page.write_text(text.rstrip() + "\n\n" + body + "\n")
        continue
    page.write_text(text.rstrip() + "\n\n" + MARK + "\n" + links + "\n")
